--[[
	Abyssara – Deep Tide Tycoon
	ApplyMeshes (Studio Command Bar script)

	GENERATED by tools/mesh-gen/make_apply_script.py – do not edit by hand,
	edit tools/mesh-gen/apply_template.lua and regenerate.

	What it does:
		Swaps the part-built models under Workspace.Assets for the smooth,
		textured meshes from assets/meshes/. Run it in Edit mode AFTER:
			1. all buildscripts in assets/models/** have been run, and
			2. every assets/meshes/<ModelName>/<ModelName>.glb has been
			   imported with the 3D Importer (File -> Import 3D) into a
			   Folder named "MeshImports" in Workspace, so that
			   Workspace.MeshImports.<ModelName> holds the MeshParts
			   (named Body, TailFin, Eye1, ...) with their SurfaceAppearance.

		Every model whose import is complete is swapped. Models without an
		import (or with missing meshes) keep their parts – nothing breaks.
		Part names, the PrimaryPart, attributes, tags, attachments,
		ProximityPrompts, lights and particles are carried over, so the
		game code and the animations (IdleSway, NpcAmbientController) work
		unchanged. Running it twice is safe: swapped models are skipped.
		MeshImports can be deleted afterwards; then save/publish the place.
]]

local Workspace = game:GetService("Workspace")
local CollectionService = game:GetService("CollectionService")

--@@LAYOUT@@

local POSITION_TOLERANCE = 0.6

local function cframeFrom(values)
	return CFrame.new(table.unpack(values))
end

local function findImport(modelName)
	local imports = Workspace:FindFirstChild("MeshImports")
	return imports and imports:FindFirstChild(modelName)
end

local function findMeshPart(container, name)
	for _, d in ipairs(container:GetDescendants()) do
		if d:IsA("MeshPart") and d.Name == name then
			return d
		end
	end
	return nil
end

-- Buildscripts reuse names ("Scale", "Spot"), so every replaced part is
-- matched by name AND by its position relative to the PrimaryPart.
local function findReplacedPart(model, base, entry, taken)
	local expected = base * Vector3.new(table.unpack(entry.Pos))
	local best, bestDist = nil, POSITION_TOLERANCE
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("BasePart") and d.Name == entry.Name and not taken[d] then
			local dist = (d.Position - expected).Magnitude
			if dist < bestDist then
				best, bestDist = d, dist
			end
		end
	end
	return best
end

local SKIPPED_CHILD_CLASSES = {
	SpecialMesh = true,
	BlockMesh = true,
	CylinderMesh = true,
	Texture = true, -- keyed tiling textures: the baked SurfaceAppearance replaces them
	Decal = true,
	SurfaceAppearance = true,
}

local function carryOver(oldPart, newPart)
	for name, value in pairs(oldPart:GetAttributes()) do
		if newPart:GetAttribute(name) == nil then
			newPart:SetAttribute(name, value)
		end
	end
	for _, tag in ipairs(CollectionService:GetTags(oldPart)) do
		CollectionService:AddTag(newPart, tag)
	end
	for _, child in ipairs(oldPart:GetChildren()) do
		if not SKIPPED_CHILD_CLASSES[child.ClassName] then
			if child:IsA("Attachment") then
				local world = child.WorldCFrame
				child.Parent = newPart
				child.WorldCFrame = world
			else
				child.Parent = newPart
			end
		end
	end
end

local function redirectJoints(model, mapping)
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("WeldConstraint") or d:IsA("JointInstance") or d:IsA("NoCollisionConstraint") then
			local p0, p1 = (d :: any).Part0, (d :: any).Part1
			if p0 and mapping[p0] then
				(d :: any).Part0 = mapping[p0]
			end
			if p1 and mapping[p1] then
				(d :: any).Part1 = mapping[p1]
			end
		end
	end
end

local function swapModel(model, layout)
	local import = findImport(model.Name)
	if not import then
		return "no import"
	end
	local primary = model.PrimaryPart
	if not primary then
		return "no PrimaryPart"
	end
	for _, mesh in ipairs(layout.Meshes) do
		if not findMeshPart(import, mesh.Name) then
			return "import is missing mesh '" .. mesh.Name .. "'"
		end
	end

	local base = primary.CFrame
	local taken = {}
	local plan = {}
	for _, mesh in ipairs(layout.Meshes) do
		local parts = {}
		for _, entry in ipairs(mesh.Replaces) do
			local part = findReplacedPart(model, base, entry, taken)
			if part then
				taken[part] = true
				table.insert(parts, part)
			end
		end
		table.insert(plan, { Mesh = mesh, Parts = parts })
	end

	local mapping = {}
	local newPrimary = nil
	for _, step in ipairs(plan) do
		local mesh = step.Mesh
		local anchor = step.Parts[1]
		for _, part in ipairs(step.Parts) do
			if part.Name == mesh.Name then
				anchor = part
				break
			end
		end

		local newPart = findMeshPart(import, mesh.Name):Clone()
		for _, child in ipairs(newPart:GetChildren()) do
			if not child:IsA("SurfaceAppearance") then
				child:Destroy()
			end
		end
		local center = base * cframeFrom(mesh.Center)
		newPart.Name = mesh.Name
		newPart.Anchored = true
		newPart.Size = Vector3.new(table.unpack(mesh.Size))
		newPart.CFrame = center
		newPart.PivotOffset = center:Inverse() * (base * cframeFrom(mesh.Pivot))
		newPart.Material = Enum.Material[mesh.Material] or Enum.Material.SmoothPlastic
		newPart.Transparency = mesh.Transparency or 0
		if anchor then
			newPart.CanCollide = anchor.CanCollide
			newPart.CanQuery = anchor.CanQuery
			newPart.CanTouch = anchor.CanTouch
			newPart.CastShadow = anchor.CastShadow
		else
			newPart.CanCollide = false
		end
		newPart.Parent = anchor and anchor.Parent or model

		for _, part in ipairs(step.Parts) do
			carryOver(part, newPart)
			mapping[part] = newPart
			if part == primary then
				newPrimary = newPart
			end
		end
	end

	redirectJoints(model, mapping)
	for sub in pairs(mapping) do
		if sub.Parent and sub.Parent:IsA("Model") and (sub.Parent :: Model).PrimaryPart == sub then
			(sub.Parent :: Model).PrimaryPart = mapping[sub]
		end
	end
	if newPrimary then
		model.PrimaryPart = newPrimary
	end
	for old in pairs(mapping) do
		old:Destroy()
	end
	model:SetAttribute("MeshSwapped", true)
	return nil
end

local assets = Workspace:FindFirstChild("Assets")
if not assets then
	warn("[ApplyMeshes] Workspace.Assets is missing – run the buildscripts first.")
	return
end

local swapped, skipped = 0, 0
for _, model in ipairs(assets:GetDescendants()) do
	local layout = model:IsA("Model") and LAYOUT[model.Name]
	if layout and not model:GetAttribute("MeshSwapped") then
		local failure = swapModel(model, layout)
		if failure then
			skipped += 1
			print(("[ApplyMeshes] %s kept its parts (%s)"):format(model:GetFullName(), failure))
		else
			swapped += 1
		end
	end
end
print(("[ApplyMeshes] swapped %d model(s), %d kept their parts. Save or publish the place now."):format(swapped, skipped))
